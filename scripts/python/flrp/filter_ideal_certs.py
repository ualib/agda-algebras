def fin(i: int) -> str:
    """A Fin literal: Data.Fin.Patterns' 0F-9F, or one of the pattern
    synonyms this module declares for the larger literals."""
    return f"{i}F"


def agda_list(entries: Sequence[str]) -> str:
    """A List/Vec literal from already-rendered entries."""
    return "(" + " ∷ ".join(tuple(entries) + ("[]",)) + ")" if entries else "[]"


def word_lit(w: Word) -> str:
    return agda_list(tuple(fin(l) for l in w))


def words_lit(ws: Sequence[Word]) -> str:
    return agda_list(tuple(word_lit(w) for w in ws))


def wrap_rows(entries: Sequence[str], per_line: int, indent: str) -> str:
    """A Vec literal, a fixed number of entries per line."""
    chunks = [entries[i:i + per_line] for i in range(0, len(entries), per_line)]
    lines = [" ∷ ".join(chunk) for chunk in chunks]
    joined = ("\n" + indent + "∷ ").join(lines)
    return "(  " + joined + "\n" + indent + "∷ [])"


def vec_block(name: str, ty: str, rows: Sequence[str]) -> str:
    body = ("\n     ∷ ").join(rows)
    return f"{name} : {ty}\n{name} =\n  (    {body}\n     ∷ [])"


def flat_block(name: str, ty: str, row: str) -> str:
    """A one-dimensional Vec literal (no outer row wrapper)."""
    return f"{name} : {ty}\n{name} =\n  {row}"


def perm_rows(gt: GroupTables) -> list[str]:
    return [agda_list(tuple(fin(x) for x in p)) for p in gt.elements]


def mul_rows(gt: GroupTables) -> list[str]:
    return [wrap_rows(tuple(fin(x) for x in row), 20, "        ") for row in gt.mul]


def chi_row(s: frozenset[int], order: int) -> str:
    return wrap_rows(tuple("true" if i in s else "false" for i in range(order)), 20, "        ")


def esc_blocks(prefix: str, esc: Escalation, m: int, order: int) -> list[str]:
    gens_rows = [agda_list(tuple(fin(l) for l in g)) for g in esc.gens]
    rank_rows = [str(r) for r in esc.ranks]
    next_rows = [wrap_rows(tuple(fin(t) for t in row), 20, "        ")
                 for row in esc.step_next]
    stepw_rows = [wrap_rows(tuple(words_lit(ws) for ws in row), 4, "        ")
                  for row in esc.step_words]
    expw_rows = [wrap_rows(tuple(word_lit(w) for w in row), 6, "        ")
                 for row in esc.exp_words]
    return [
        vec_block(f"{prefix}Gens", f"Vec (List (Fin {order})) {m}", gens_rows),
        vec_block(f"{prefix}Rank", f"Vec ℕ {m}", rank_rows),
        vec_block(f"{prefix}StepNext", f"Vec (Vec (Fin {m}) {order}) {m}", next_rows),
        vec_block(f"{prefix}StepWords",
                  f"Vec (Vec (List (List (Fin {order}))) {order}) {m}", stepw_rows),
        vec_block(f"{prefix}ExpWords", f"Vec (Vec (List (Fin {order})) {order}) {m}", expw_rows),
    ]


