def build_all() -> str:
    gt = group_tables()
    sd = subgroup_data(gt)
    check_interval_facts(gt, sd)
    check_l16_tables(sd)

    # Family numbering: filter [C3, S3, A4, A4', A5] with ranks 0,1,1,1,2;
    # ideal [1, C5] with ranks 0,1.  Ranks stay below the family size, and
    # every certified step strictly increases them.
    filt = build_escalation(
        gt,
        member_sets=[sd.sets[1], sd.sets[3], sd.sets[4], sd.sets[5], sd.sets[6]],
        member_gens=[sd.gens[1], sd.gens[3], sd.gens[4], sd.gens[5], sd.gens[6]],
        ranks=[0, 1, 1, 1, 2],
        top=sd.sets[6],
    )
    ideal = build_escalation(
        gt,
        member_sets=[sd.sets[0], sd.sets[2]],
        member_gens=[sd.gens[0], sd.gens[2]],
        ranks=[0, 1],
        top=sd.sets[2],
    )
    return build_module_text(gt, sd, filt, ideal)


def main(argv: Sequence[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT,
                        help="output .lagda.md (default: %(default)s)")
    args = parser.parse_args(argv)

    text = build_all()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    print(f"wrote {args.output} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
