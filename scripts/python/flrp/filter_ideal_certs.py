import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Iterator, Mapping, Sequence

Perm = tuple[int, ...]
Word = tuple[int, ...]

REPO_ROOT = Path(__file__).resolve().parents[3]
DEFAULT_OUTPUT = REPO_ROOT / "src" / "FLRP" / "Certificates" / "FilterIdeal" / "A5Data.lagda.md"
L16_LATTICE_JSON = Path(__file__).resolve().parent / "inputs" / "slr" / "slr16_lattice.json"

DEGREE = 5
STDLIB_FIN_PATTERNS = 10


# --------------------------------------------------------------------------
# The group A5 on Fin 5, elements canonically ordered
# --------------------------------------------------------------------------

def compose(u: Perm, v: Perm) -> Perm:
    """u after v, matching Agda's `compose u v = tabulate (λ p → lookup u (lookup v p))`."""
    return tuple(u[v[p]] for p in range(len(v)))


def parity(p: Perm) -> int:
    """0 for even permutations, 1 for odd (by counting inversions)."""
    inversions = sum(1 for i, j in itertools.combinations(range(len(p)), 2) if p[i] > p[j])
    return inversions % 2


def a5_elements() -> tuple[Perm, ...]:
    """The 60 even permutations of {0..4}, lexicographically sorted, so the
    identity is element 0."""
    return tuple(sorted(p for p in itertools.permutations(range(DEGREE)) if parity(p) == 0))


def inverse(p: Perm) -> Perm:
    inv = [0] * len(p)
    for i, pi in enumerate(p):
        inv[pi] = i
    return tuple(inv)


@dataclass(frozen=True)
class GroupTables:
    """A5 with its canonical numbering and multiplication/inverse tables."""
    elements: tuple[Perm, ...]
    index: Mapping[Perm, int]
    mul: tuple[tuple[int, ...], ...]
    inv: tuple[int, ...]

    @property
    def order(self) -> int:
        return len(self.elements)


def group_tables() -> GroupTables:
    elements = a5_elements()
    index = {p: i for i, p in enumerate(elements)}
    mul = tuple(tuple(index[compose(u, v)] for v in elements) for u in elements)
    inv = tuple(index[inverse(p)] for p in elements)
    return GroupTables(elements=elements, index=index, mul=mul, inv=inv)


# --------------------------------------------------------------------------
# Subgroups
# --------------------------------------------------------------------------

def cycle(points: Sequence[int]) -> Perm:
    """The cycle sending points[i] to points[i+1], fixing everything else."""
    image = list(range(DEGREE))
    for a, b in zip(points, tuple(points[1:]) + (points[0],)):
        image[a] = b
    return tuple(image)


def closure(gens: frozenset[int], mul: Sequence[Sequence[int]]) -> frozenset[int]:
    """The subgroup generated by the given element indices (0 is the identity)."""
    reached = {0} | set(gens)
    frontier = list(reached)
    while frontier:
        x = frontier.pop()
        for g in gens:
            y = mul[x][g]
            if y not in reached:
                reached.add(y)
                frontier.append(y)
    # A finite set closed under right multiplication by generators need not be
    # a subgroup in general, but it is here because it contains the identity
    # and each generator has finite order; assert closure under the full
    # multiplication for safety.
    assert all(mul[a][b] in reached for a in reached for b in reached)
    return frozenset(reached)


@dataclass(frozen=True)
class SubgroupData:
    """The seven subgroups presenting L16, in census numbering."""
    names: tuple[str, ...]           # trivial, C3, C5, S3, A4, A4', A5
    sets: tuple[frozenset[int], ...]
    gens: tuple[tuple[int, ...], ...]


def subgroup_data(gt: GroupTables) -> SubgroupData:
    c3 = gt.index[cycle((0, 1, 2))]
    c5 = gt.index[cycle((0, 1, 2, 3, 4))]
    t = gt.index[compose(cycle((0, 1)), cycle((3, 4)))]      # (0 1)(3 4)
    d = gt.index[compose(cycle((0, 1)), cycle((2, 3)))]      # (0 1)(2 3)
    d2 = gt.index[compose(cycle((0, 1)), cycle((2, 4)))]     # (0 1)(2 4)

    gens: tuple[tuple[int, ...], ...] = (
        (),            # trivial
        (c3,),         # C3
        (c5,),         # C5
        (c3, t),       # S3 = normalizer of C3
        (c3, d),       # A4 on {0,1,2,3}
        (c3, d2),      # A4' on {0,1,2,4}
        (c3, c5),      # A5
    )
    sets = tuple(closure(frozenset(g), gt.mul) for g in gens)
    names = ("1", "C3", "C5", "S3", "A4", "A4'", "A5")

    assert tuple(len(s) for s in sets) == (1, 3, 5, 6, 12, 12, 60)
    return SubgroupData(names=names, sets=sets, gens=gens)


def check_interval_facts(gt: GroupTables, sd: SubgroupData) -> None:
    """The group-theoretic shape behind L16, re-verified from scratch."""
    triv, c3, c5, s3, a4, a4b, a5 = sd.sets
    middles = (s3, a4, a4b)

    # [C3, A5] has exactly the three middles: adjoining any element off C3
    # generates a middle or all of A5, and the middles are incomparable.
    for g in range(gt.order):
        if g not in c3:
            gen = closure(c3 | {g}, gt.mul)
            assert gen in middles or gen == a5, f"unexpected subgroup over C3 at {g}"
    assert all(not (m1 < m2) for m1 in middles for m2 in middles if m1 != m2)

    # The middles are maximal: adjoining any outside element generates A5.
    for m in middles:
        for g in range(gt.order):
            if g not in m:
                assert closure(m | {g}, gt.mul) == a5, f"middle not maximal at {g}"

    # C5 meets each middle trivially and joins each to A5 (the L16 shape),
    # and C5 is C3-free.
    for m in middles:
        assert c5 & m == triv
        assert closure(frozenset(sd.gens[2]) | m, gt.mul) == a5
    assert not (c3 <= c5)


def check_l16_tables(sd: SubgroupData) -> None:
    """The subgroup order under the census numbering reproduces the meet and
    join tables of slr16_lattice.json."""
    tables = json.loads(L16_LATTICE_JSON.read_text())
    sets = sd.sets
    n = len(sets)

    def meet(i: int, j: int) -> int:
        return next(k for k in range(n) if sets[k] == sets[i] & sets[j])

    def join(i: int, j: int) -> int:
        candidates = [k for k in range(n) if sets[i] | sets[j] <= sets[k]]
        return min(candidates, key=lambda k: len(sets[k]))

    assert [[meet(i, j) for j in range(n)] for i in range(n)] == tables["meet"]
    assert [[join(i, j) for j in range(n)] for i in range(n)] == tables["join"]


# --------------------------------------------------------------------------
# Escalation certificates
# --------------------------------------------------------------------------

def bfs_words(letters: Sequence[int], mul: Sequence[Sequence[int]],
              wanted: frozenset[int]) -> dict[int, Word]:
    """Shortest words over the letters (as left-to-right products, matching
    Agda's evalWord) reaching every wanted element from the identity."""
    words: dict[int, Word] = {0: ()}
    queue: list[int] = [0]
    while queue and not wanted <= words.keys():
        x = queue.pop(0)
        for letter in letters:
            y = mul[x][letter]
            if y not in words:
                words[y] = words[x] + (letter,)
                queue.append(y)
    missing = wanted - words.keys()
    assert not missing, f"letters do not generate the wanted elements: {missing}"
    return {y: w for y, w in words.items() if y in wanted}


@dataclass(frozen=True)
class Escalation:
    """Certificate data for one family, in the Escalate schema: per member a
    generator list, a rank, and per carrier index a step target, step words
    (one per generator of the target), and an expansion word."""
    member_sets: tuple[frozenset[int], ...]
    gens: tuple[tuple[int, ...], ...]
    ranks: tuple[int, ...]
    step_next: tuple[tuple[int, ...], ...]
    step_words: tuple[tuple[tuple[Word, ...], ...], ...]
    exp_words: tuple[tuple[Word, ...], ...]


def build_escalation(gt: GroupTables,
                     member_sets: Sequence[frozenset[int]],
                     member_gens: Sequence[tuple[int, ...]],
                     ranks: Sequence[int],
                     top: frozenset[int]) -> Escalation:
    """Compute the words for one interval family.  Step rows are only
    meaningful for indices inside `top` and off the member; other rows get
    the dummy (member itself, no words)."""
    m = len(member_sets)

    def exp_row(k: int) -> tuple[Word, ...]:
        words = bfs_words(member_gens[k], gt.mul, member_sets[k])
        return tuple(words.get(i, ()) for i in range(gt.order))

    def step_target(k: int, j: int) -> int:
        generated = closure(member_sets[k] | {j}, gt.mul)
        matches = [t for t in range(m) if member_sets[t] <= generated and ranks[t] > ranks[k]]
        assert matches, f"no escalation target for member {k} with element {j}"
        # The largest-rank member inside the generated subgroup keeps the
        # walk short; any valid choice would do.
        exact = [t for t in matches if member_sets[t] == generated]
        return exact[0] if exact else max(matches, key=lambda t: ranks[t])

    def step_row(k: int) -> tuple[tuple[int, ...], tuple[tuple[Word, ...], ...]]:
        nexts = []
        words = []
        for j in range(gt.order):
            if j in top and j not in member_sets[k]:
                t = step_target(k, j)
                reach = bfs_words((j,) + member_gens[k], gt.mul,
                                  frozenset(member_gens[t]))
                nexts.append(t)
                words.append(tuple(reach[g] for g in member_gens[t]))
            else:
                nexts.append(k)
                words.append(())
        return tuple(nexts), tuple(words)

    rows = tuple(step_row(k) for k in range(m))
    return Escalation(
        member_sets=tuple(member_sets),
        gens=tuple(member_gens),
        ranks=tuple(ranks),
        step_next=tuple(r[0] for r in rows),
        step_words=tuple(r[1] for r in rows),
        exp_words=tuple(exp_row(k) for k in range(m)),
    )


