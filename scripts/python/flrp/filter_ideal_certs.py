def pattern_block(max_fin: int) -> str:
    return "\n".join(f"pattern {i}F = suc {i - 1}F"
                     for i in range(STDLIB_FIN_PATTERNS, max_fin + 1))


def code_section(title: str, blocks: Sequence[str]) -> str:
    body = "\n\n".join(blocks)
    return f"#### {title}\n\n```agda\n{body}\n```\n"


def build_module_text(gt: GroupTables, sd: SubgroupData,
                      filt: Escalation, ideal: Escalation) -> str:
    order = gt.order
    header = MODULE_HEADER.replace("{PATTERNS}", pattern_block(order - 1))

    group_blocks = [
        vec_block("permVecs", f"Vec (Vec (Fin {DEGREE}) {DEGREE}) {order}", perm_rows(gt)),
        vec_block("mulVecs", f"Vec (Vec (Fin {order}) {order}) {order}", mul_rows(gt)),
        flat_block("invVec", f"Vec (Fin {order}) {order}",
                   wrap_rows(tuple(fin(x) for x in gt.inv), 20, "        ")),
    ]

    chi_names = ("chi1", "chiC3", "chiC5", "chiS3", "chiA4", "chiA4'", "chiA5")
    chi_blocks = [flat_block(name, f"Vec Bool {order}", chi_row(s, order))
                  for name, s in zip(chi_names, sd.sets)]

    sections = [
        code_section("The group tables", group_blocks),
        code_section("The seven subgroups, as characteristic vectors", chi_blocks),
        code_section("The filter family [C3 , A5]: C3 , S3 , A4 , A4' , A5",
                     esc_blocks("filter", filt, 5, order)),
        code_section("The ideal family [1 , C5]: 1 , C5",
                     esc_blocks("ideal", ideal, 2, order)),
    ]
    return header + "\n" + "\n".join(sections) + "\n--------------------------------------\n"


