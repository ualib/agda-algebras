"""
File: scripts/python/flrp/filter_ideal_certs.py

Description: Emit the A5 certificate data module for the Snow filter-ideal
  route to census entry L16 (issue #530).

  The new witness represents L16 as the union of the filter [C3, A5] and the
  ideal [1, C5] inside Sub(A5).
  Classical.Structures.Group.SubgroupClassification consumes, and re-verifies
  by decision, the concrete data this script computes:

  + the alternating group A5 as 60 permutation image-vectors on 5 points,
    its multiplication and inverse tables (associativity is certified in Agda
    through the faithful action, so no cubic sweep runs there);
  + characteristic vectors of the seven subgroups 1, C3, C5, S3, A4, A4',
    A5 that carry L16;
  + escalation certificates for the two interval families: generators,
    ranks, step targets, step words, and expansion words, in the schema of
    Classical.Structures.Group.SubgroupClassification.Escalate.

  Every engine-side claim is re-checked here by assertion (group axioms,
  subgroup closure, the three-middles interval fact, maximality of the
  middles, and agreement of the subgroup order with the meet/join tables of
  inputs/slr/slr16_lattice.json), and then re-checked *again* in Agda, where
  a wrong word makes a decidable check compute to `no` and break compilation.

Provenance: authored for issue #530; the emitted module is
  src/FLRP/Certificates/FilterIdeal/A5Data.lagda.md.
"""

